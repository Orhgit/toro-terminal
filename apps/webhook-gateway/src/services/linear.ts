/**
 * Creates a Linear issue for the marketing team with the full
 * AI pipeline output — property data, vision tags, and marketing copy.
 *
 * Requires LINEAR_API_KEY and LINEAR_TEAM_ID in env.
 */
export async function createMarketingTask(
  pipelineResult: PipelineResult
): Promise<LinearTaskResult> {
  const teamId = await fetchTeamId();
  const { property, vision, copy } = pipelineResult;

  const sections: string[] = [
    `## Property Data`,
    `| Field | Value |`,
    `|-------|-------|`,
    `| Phone | ${property.owner_phone} |`,
    `| Price | ₪${property.price_asked.toLocaleString("he-IL")} |`,
    `| Status | ${property.status} |`,
  ];

  if (vision) {
    sections.push(
      ``,
      `## Vision Analysis`,
      `**Quality Score:** ${vision.qualityScore}/10`,
      `**Room Tags:** ${vision.roomTags.join(", ")}`
    );
  }

  sections.push(
    ``,
    `## Marketing Copy`,
    `**Hook:** ${copy.shortHook}`,
    ``,
    copy.fullDescription
  );

  const body = sections.join("\n");

  const data = await linearGql<{
    issueCreate: { success: boolean; issue: { id: string; identifier: string; url: string } | null };
  }>(CREATE_ISSUE_MUTATION, {
    input: { teamId, title: copy.shortHook, description: body },
  });

  const issue = data.issueCreate.issue;
  if (!data.issueCreate.success || !issue) {
    throw new Error("Linear issue creation failed — no issue returned");
  }

  return { issueId: issue.id, identifier: issue.identifier, url: issue.url };
}
