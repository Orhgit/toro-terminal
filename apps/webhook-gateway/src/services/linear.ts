import type { PipelineResult } from "@repo/ai-core/orchestrator";

// ============================================================
// Types
// ============================================================

interface LinearIssueResponse {
  data?: {
    issueCreate: {
      success: boolean;
      issue: {
        id: string;
        identifier: string;
        url: string;
      } | null;
    };
  };
  errors?: Array<{ message: string }>;
}

interface LinearTaskResult {
  issueId: string;
  identifier: string;
  url: string;
}

// ============================================================
// GraphQL
// ============================================================

const CREATE_ISSUE_MUTATION = `
  mutation IssueCreate($input: IssueCreateInput!) {
    issueCreate(input: $input) {
      success
      issue {
        id
        identifier
        url
      }
    }
  }
`;

// ============================================================
// GraphQL — team lookup
// ============================================================

const TEAMS_QUERY = `
  query {
    teams {
      nodes {
        id
        name
        key
      }
    }
  }
`;

// ============================================================
// Helpers
// ============================================================

function getLinearHeaders(): Record<string, string> {
  const apiKey = process.env.LINEAR_API_KEY;
  if (!apiKey) throw new Error("Missing LINEAR_API_KEY environment variable");
  return {
    "Content-Type": "application/json",
    Authorization: apiKey,
  };
}

async function linearGql<T>(query: string, variables?: Record<string, unknown>): Promise<T> {
  const response = await fetch("https://api.linear.app/graphql", {
    method: "POST",
    headers: getLinearHeaders(),
    body: JSON.stringify({ query, variables }),
  });

  if (!response.ok) {
    throw new Error(`Linear API returned ${response.status}: ${response.statusText}`);
  }

  const result = (await response.json()) as { data?: T; errors?: Array<{ message: string }> };

  if (result.errors?.length) {
    throw new Error(`Linear GraphQL errors: ${result.errors.map((e) => e.message).join(", ")}`);
  }

  if (!result.data) throw new Error("Linear returned no data");
  return result.data;
}

// ============================================================
// Public API — Team discovery
// ============================================================

/**
 * Fetch the 'Toro' team ID from Linear automatically.
 * Falls back to LINEAR_TEAM_ID env if no 'Toro' team is found.
 */
export async function fetchTeamId(): Promise<string> {
  // If explicitly set, use it
  if (process.env.LINEAR_TEAM_ID) return process.env.LINEAR_TEAM_ID;

  const data = await linearGql<{ teams: { nodes: Array<{ id: string; name: string; key: string }> } }>(TEAMS_QUERY);

  const toroTeam = data.teams.nodes.find(
    (t) => t.name.toLowerCase().includes("toro") || t.key.toLowerCase().includes("toro")
  );

  if (toroTeam) return toroTeam.id;

  // Fallback to first team
  const first = data.teams.nodes[0];
  if (first) return first.id;

  throw new Error("No Linear teams found — create a team or set LINEAR_TEAM_ID");
}

