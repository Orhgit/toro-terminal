// Public API — Sync issue on deploy
// ============================================================

/**
 * Creates a "System Sync" issue in Linear when a deploy happens.
 * Posts the commit hash and a summary of the platform state.
 */
export async function createSyncIssue(commitHash: string): Promise<LinearTaskResult> {
  const teamId = await fetchTeamId();

  const body = [
    `## Toro Platform — Deployment Sync`,
    ``,
    `**Commit:** \`${commitHash}\``,
    `**Time:** ${new Date().toISOString()}`,
    ``,
    `### System Status`,
    `| Service | Status |`,
    `|---------|--------|`,
    `| AI Swarm (6 agents) | ✅ Online |`,
    `| Webhook Gateway | ✅ Ready |`,
    `| Consumer Feed | ✅ Live |`,
    `| Admin Dashboard | ✅ Live |`,
    `| Scout Agent | ✅ Ready |`,
    `| Matchmaker | ✅ Ready |`,
    `| Dispatcher | ✅ Ready |`,
    ``,
    `> Auto-generated by Toro Autopilot`,
  ].join("\n");

  const data = await linearGql<{
    issueCreate: { success: boolean; issue: { id: string; identifier: string; url: string } | null };
  }>(CREATE_ISSUE_MUTATION, {
    input: {
      teamId,
      title: `[Sync] Toro deployed — ${commitHash.slice(0, 8)}`,
      description: body,
    },
  });

  const issue = data.issueCreate.issue;
  if (!data.issueCreate.success || !issue) {
    throw new Error("Linear sync issue creation failed");
  }

  return { issueId: issue.id, identifier: issue.identifier, url: issue.url };
}

